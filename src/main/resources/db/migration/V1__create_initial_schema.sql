-- =========================================================
-- 1. USERS
-- =========================================================

CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,

    full_name VARCHAR(100) NOT NULL,

    email VARCHAR(255) NOT NULL,

    hashed_password VARCHAR(255) NOT NULL,

    role VARCHAR(20) NOT NULL DEFAULT 'customer',

    phone VARCHAR(20) NOT NULL,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMP(6) WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_users PRIMARY KEY (id),

    CONSTRAINT uk_users_email UNIQUE (email),

    CONSTRAINT uk_users_phone UNIQUE (phone),

    CONSTRAINT ck_users_role
        CHECK (role IN ('admin', 'customer', 'barber'))
);


-- =========================================================
-- 2. SESSION TOKENS
-- =========================================================

CREATE TABLE session_tokens (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,

    user_id INTEGER NOT NULL,

    refresh_token_hash VARCHAR(255) NOT NULL,

    last_activity_at TIMESTAMP(6) WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    expired_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,

    revoked_at TIMESTAMP(6) WITH TIME ZONE NULL,

    created_at TIMESTAMP(6) WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_session_tokens PRIMARY KEY (id),

    CONSTRAINT uk_session_tokens_refresh_hash
        UNIQUE (refresh_token_hash),

    CONSTRAINT fk_session_tokens_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE
);


-- =========================================================
-- 3. SERVICES
-- =========================================================

CREATE TABLE services (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,

    name VARCHAR(100) NOT NULL,

    description TEXT NULL,

    price NUMERIC(10, 2) NOT NULL,

    duration_minutes INTEGER NOT NULL,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_services PRIMARY KEY (id)
);


-- =========================================================
-- 4. BARBER SCHEDULES
-- =========================================================

CREATE TABLE barber_schedules (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,

    barber_id INTEGER NOT NULL,

    date_of_week INTEGER NOT NULL,

    start_time TIME NOT NULL,

    end_time TIME NOT NULL,

    is_off BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT pk_barber_schedules PRIMARY KEY (id),

    CONSTRAINT ck_barber_schedules_day
        CHECK (date_of_week BETWEEN 0 AND 6),

    CONSTRAINT fk_barber_schedules_barber
        FOREIGN KEY (barber_id)
        REFERENCES users(id)
        ON DELETE CASCADE
);


-- =========================================================
-- 5. BOOKINGS
-- =========================================================

CREATE TABLE bookings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,

    customer_id INTEGER NOT NULL,

    barber_id INTEGER NOT NULL,

    booking_date DATE NOT NULL,

    start_time TIME NOT NULL,

    end_time TIME NOT NULL,

    total_price NUMERIC(10, 2) NOT NULL,

    status VARCHAR(20) NOT NULL,

    created_at TIMESTAMP(6) WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_bookings PRIMARY KEY (id),

    CONSTRAINT ck_bookings_status
        CHECK (
            status IN (
                'pending',
                'confirmed',
                'completed',
                'cancelled'
            )
        ),

    CONSTRAINT fk_bookings_customer
        FOREIGN KEY (customer_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_bookings_barber
        FOREIGN KEY (barber_id)
        REFERENCES users(id)
        ON DELETE CASCADE
);


-- =========================================================
-- BOOKING INDEX
-- =========================================================

CREATE INDEX idx_bookings_barber_date
    ON bookings (barber_id, booking_date);


-- =========================================================
-- 6. BOOKING SERVICES
-- =========================================================

CREATE TABLE booking_services (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,

    booking_id INTEGER NOT NULL,

    service_id INTEGER NOT NULL,

    price_at_booking NUMERIC(10, 2) NOT NULL,

    CONSTRAINT pk_booking_services PRIMARY KEY (id),

    CONSTRAINT uk_booking_service
        UNIQUE (booking_id, service_id),

    CONSTRAINT fk_booking_services_booking
        FOREIGN KEY (booking_id)
        REFERENCES bookings(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_booking_services_service
        FOREIGN KEY (service_id)
        REFERENCES services(id)
        ON DELETE CASCADE
);